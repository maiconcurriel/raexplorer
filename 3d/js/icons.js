window.bioIcon = function (name, size = 24) {
    const paths = BIO_ICONS[name];

    if (!paths) {
        console.warn(`[BioExplora] Ícone não encontrado: ${name}`);
        return '';
    }

    return `
        <svg
            xmlns="http://www.w3.org/2000/svg"
            class="bio-icon"
            width="${size}"
            height="${size}"
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            stroke-width="1.8"
            stroke-linecap="round"
            stroke-linejoin="round"
            aria-hidden="true"
        >
            ${paths}
        </svg>
    `;
};


/* ============================================
   RENDERIZAÇÃO AUTOMÁTICA DOS ÍCONES
   ============================================ */

window.renderBioIcons = function (root = document) {

    // Permite renderizar o próprio elemento recebido.
    const elements = [];

    if (root.matches && root.matches('[data-icon]')) {
        elements.push(root);
    }

    elements.push(...root.querySelectorAll('[data-icon]'));

    elements.forEach(element => {
        const name = element.dataset.icon;

        element.innerHTML = window.bioIcon(name);
    });
};


/* ============================================
   INICIALIZAÇÃO
   ============================================ */

function initBioIcons() {
    window.renderBioIcons();
}

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initBioIcons);
} else {
    initBioIcons();
}
